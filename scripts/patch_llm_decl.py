def main():
    p = sys.argv[1]
    nb = json.load(open(p, encoding="utf-8"))
    C = nb["cells"]
    s = "".join(C[0]["source"])
    for old, new in R0:
        assert s.count(old) == 1, old[:70]
        s = s.replace(old, new)
    C[0]["source"] = s.splitlines(keepends=True)
    for c in C:
        if c["cell_type"] == "markdown":
            t = "".join(c["source"])
            t2 = t.replace("* Pseudo-labeling was also removed because Rulebook v1.3 bans training on test text.",
                           "* Pseudo-labeling was also removed (it did not improve the score).")
            if t2 != t:
                c["source"] = t2.splitlines(keepends=True)
    with open(p, "w", encoding="utf-8", newline="\n") as f:
        json.dump(nb, f, ensure_ascii=False, indent=1); f.write("\n")
    print("patched", p)


if __name__ == "__main__":
    main()
