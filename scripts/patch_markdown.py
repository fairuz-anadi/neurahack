def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("notebook")
    ap.add_argument("--xlmr", choices=["base", "large"], required=True)
    ap.add_argument("--prints", action="store_true", help="also apply the print fixes to code cells (repo copies only)")
    ap.add_argument("--out", help="write here instead of overwriting")
    a = ap.parse_args()
    v = XLMR[a.xlmr]
    nb = json.load(open(a.notebook, encoding="utf-8"))
    cells = nb["cells"]
    if cells[0]["cell_type"] != "markdown":
        sys.exit("first cell is not markdown: refusing (check the notebook)")
    src = lambda c: "".join(c["source"])
    model_in_nb = [m for m in ("xlm-roberta-large", "xlm-roberta-base") if f'"SS_MODEL", "{m}"' in "".join(src(c) for c in cells)]
    if model_in_nb and model_in_nb[0] != v["model"]:
        sys.exit(f"--xlmr {a.xlmr} but the notebook's default MODEL_NAME is {model_in_nb[0]}")

    cells[0]["source"] = DECLARATION.format(**v).rstrip("\n").splitlines(keepends=True)
    review = {"cell_type": "markdown", "metadata": {}, "source": REVIEW.format(**v).rstrip("\n").splitlines(keepends=True)}
    if cells[-1]["cell_type"] == "markdown" and src(cells[-1]).startswith("# Review"):
        cells[-1] = review
    else:
        cells.append(review)

    if a.prints:
        n = 0
        for c in cells:
            if c["cell_type"] != "code":
                continue
            s = src(c)
            if "print(chk.head())" in s:
                s = s.replace("print(chk.head())", 'print("confidence mean:", round(float(chk["confidence"].mean()), 4), "| NONE share:", round(float((chk["techniques"] == "NONE").mean()), 4))'); n += 1
            if "import sklearn, scipy\n" in s and 'print("numpy", np.__version__,' in s:
                s = s.replace("import sklearn, scipy\n", "import sys, sklearn, scipy\n").replace(
                    'print("numpy", np.__version__,', 'print("python", sys.version.split()[0], "| numpy", np.__version__,'); n += 1
            c["source"] = s.splitlines(keepends=True)
        print(f"print fixes applied: {n}")
        if n:
            cells[0]["source"] = "".join(cells[0]["source"]).replace(
                "The setup cell (section 1) prints numpy,", "The setup cell (section 1) prints python, numpy,").splitlines(keepends=True)

    out = a.out or a.notebook
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        json.dump(nb, f, ensure_ascii=False, indent=1); f.write("\n")
    print(f"wrote {out}: declaration ({v['model']}) + Review, {len(cells)} cells")


if __name__ == "__main__":
    main()
